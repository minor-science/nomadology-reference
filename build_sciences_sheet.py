def rec(q, key):
    n = NOTES.get((q, key))
    if not n:
        return ""
    i = NOTE_ID[(q, key)]
    if g.MODE["print"]:
        return f'<sup class="rmark">R{i}</sup>'
    return f'<span class="rec"><b class="rid">R{i}</b> {fmt(n)}</span>'


def cell(key, val, q):
    cls = "bd" if key == "border" else ""
    if val.startswith("EXT:"):
        return f'<td class="ext">{fmt(val[4:])}</td>'
    return f'<td class="{cls}">{fmt(val)}{rec(q, key)}</td>'


def grid():
    out = ['<table><colgroup><col class="q"><col><col><col></colgroup><thead><tr><th>Question</th>']
    for c in COLS:
        t, s = HEAD[c]
        out.append(f'<th class="{"bd" if c == "border" else ""}">{t}<small>{s}</small></th>')
    out.append("</tr></thead><tbody>")
    for q, vals in ROWS:
        out.append(f'<tr class="row"><th>{q}</th>' + "".join(cell(c, vals[c], q) for c in COLS) + "</tr>")
    out.append(f'<tr class="meet"><th>How do the two meet?</th><td colspan="3">{fmt(MEET)}</td></tr></tbody></table>')
    return "".join(out)


def qtable():
    out = ['<table class="qs"><colgroup><col class="ins"><col class="ask"><col class="pp"><col></colgroup>'
           '<thead><tr><th>Instead of asking</th><th>A nomadology asks</th><th>ATP</th><th>A case</th></tr></thead><tbody>']
    for grp, rows in QUESTIONS:
        out.append(f'<tr class="grp"><th colspan="4">{grp}</th></tr>')
        for inst, ask, pp, case in rows:
            out.append(f'<tr class="row"><td class="inst">{fmt(inst)}</td><td class="ask">{fmt(ask)}</td><td class="pp">{pp}</td><td>{fmt(case)}</td></tr>')
    out.append("</tbody></table>")
    return "".join(out)


