def text_dump():
    """Plain text of every cell, for the voice and quotation checks."""
    lines = [INTRO, INTRO_Q, MEET]
    for q, vals in ROWS:
        lines += [vals[c].replace("EXT:", "") for c in COLS]
    lines += list(NOTES.values())
    for _, rows in QUESTIONS:
        for inst, ask, pp, case in rows:
            lines += [inst, ask, case]
    lines += [d for _, d in KEY_NEW]
    t = "\n\n".join(lines)
    for a, b in (("**", ""), ("[[", "("), ("]]", ")"), ("<i>", "*"), ("</i>", "*"), ("<b>", ""), ("</b>", "")):
        t = t.replace(a, b)
    return t


